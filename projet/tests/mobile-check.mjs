import { chromium } from 'playwright';
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 390, height: 844 } });
await p.goto('http://localhost:5173/', { waitUntil: 'networkidle' });
await p.evaluate(() => {
  const s = window.__cq.server;
  s.resetDemo(); s.setDemoClock(0);
  s.signIn('trystan@famille-noel.fr', 'noel2026');
  ['rose','bleue','doree','violette'].forEach(k => s.adminSetKey('u-maman', k, true, true));
  s.signOut();
});
await p.reload({ waitUntil: 'networkidle' });
await p.getByRole('button', { name: /Maman/ }).first().click();
await p.locator('input[type=password]').fill('noel2026');
await p.locator('input[type=checkbox]').check();
await p.getByRole('button', { name: /Entrer dans le village/ }).click();
await p.waitForTimeout(1800);
await p.screenshot({ path: 'shots/40-mobile-village.png' });
const box = await p.getByRole('button', { name: /Mes listes/ }).boundingBox();
console.log('BOUTON LISTES', box);
await p.getByRole('button', { name: /Mes listes/ }).click();
await p.waitForTimeout(1200);
await p.screenshot({ path: 'shots/41-mobile-listes.png' });
await b.close();
