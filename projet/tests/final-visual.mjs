import { chromium } from 'playwright';
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 1440, height: 900 } });
p.on('pageerror', e => console.log('PAGEERROR', e.message));
await p.goto('http://localhost:5173/', { waitUntil: 'networkidle' });
await p.evaluate(() => {
  const s = window.__cq.server;
  s.resetDemo(); s.setDemoClock(0); s.setSimulatedReveal(false);
  s.signIn('trystan@famille-noel.fr', 'noel2026');
  ['rose', 'bleue', 'doree', 'violette'].forEach(k => s.adminSetKey('u-maman', k, true, true));
  s.signOut();
});
await p.waitForTimeout(400);
await p.getByRole('button', { name: /Maman/ }).first().click();
await p.locator('input[type=password]').fill('noel2026');
await p.locator('input[type=checkbox]').check();
await p.getByRole('button', { name: /Entrer dans le village/ }).click();
await p.waitForTimeout(2200);
await p.screenshot({ path: 'shots/30-village-coffre-ouvert.png' });
await p.getByRole('button', { name: /Mes listes/ }).click();
await p.waitForTimeout(1200);
await p.screenshot({ path: 'shots/31-listes-desktop.png' });
// basculer le mode simulation de révélation
await p.locator('.demo-switch input').check();
await p.waitForTimeout(900);
await p.screenshot({ path: 'shots/32-listes-revelees.png' });
const mobile = await b.newPage({ viewport: { width: 390, height: 844 } });
await mobile.goto('http://localhost:5173/', { waitUntil: 'networkidle' });
await mobile.getByRole('button', { name: /Maman/ }).first().click();
await mobile.locator('input[type=password]').fill('noel2026');
await mobile.locator('input[type=checkbox]').check();
await mobile.getByRole('button', { name: /Entrer dans le village/ }).click();
await mobile.waitForTimeout(1500);
await mobile.getByRole('button', { name: /Mes listes/ }).click();
await mobile.waitForTimeout(1000);
await mobile.screenshot({ path: 'shots/33-mobile-listes.png', fullPage: false });
await b.close();
