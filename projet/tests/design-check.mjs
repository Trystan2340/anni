import { chromium } from 'playwright';
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 1280, height: 800 } });
const errors = [];
p.on('pageerror', e => errors.push(e.message));
await p.goto('http://localhost:5173/', { waitUntil: 'networkidle' });
await p.waitForTimeout(700);
await p.screenshot({ path: 'shots/70-login-propre.png' });
// aucune icône emoji audio ne doit subsister
const emojiLeft = await p.locator('text=🔊, text=🔇, text=🎵').count();
const audioText = await p.locator('.audio-settings').innerText().catch(() => 'absent');
await p.getByRole('button', { name: /Maman/ }).first().click();
await p.locator('input[type=password]').fill('noel2026');
await p.locator('input[type=checkbox]').check();
await p.getByRole('button', { name: /Entrer dans le village/ }).click();
await p.waitForTimeout(2600);
await p.screenshot({ path: 'shots/71-village-propre.png' });
await p.getByRole('button', { name: /Pause/ }).click();
await p.waitForTimeout(500);
await p.screenshot({ path: 'shots/72-pause.png' });
await p.getByRole('button', { name: /Reprendre la partie/ }).click();
await p.waitForTimeout(400);
await p.evaluate(() => window.__cq.openMinigame('maman'));
await p.waitForTimeout(1000);
await p.keyboard.press('Enter');
await p.waitForTimeout(1200);
await p.screenshot({ path: 'shots/73-match3-propre.png' });
console.log('Emoji audio restants :', emojiLeft);
console.log('Réglages audio (texte) :', audioText.replace(/\n/g, ' '));
console.log('Erreurs JS :', errors.length ? errors : 'aucune');
await b.close();
